# Band x size mixed-effects logistic regression on the vessel-level long table.
# Usage: Rscript scripts/vessel/mixed_model.R <vessel_long_untreated.csv> <out_dir>
suppressPackageStartupMessages(library(lme4))
a <- commandArgs(trailingOnly = TRUE); infile <- a[1]; outdir <- a[2]
dir.create(outdir, showWarnings = FALSE, recursive = TRUE)
L <- read.csv(infile)
L$band <- relevel(factor(L$band), ref = "B04")
L$severity <- factor(L$severity)
L$log_area_c <- L$log_area - mean(L$log_area)
ctrl <- glmerControl(optimizer = "bobyqa", optCtrl = list(maxfun = 2e5))
m0 <- glmer(detected ~ band + log_area_c + severity + (1 | scene) + (1 | vessel_id), data = L, family = binomial, control = ctrl)
m1 <- glmer(detected ~ band * log_area_c + severity + (1 | scene) + (1 | vessel_id), data = L, family = binomial, control = ctrl)
sink(file.path(outdir, "mixed_model.txt"))
cat("Rows:", nrow(L), " vessels:", length(unique(L$vessel_id)), " scenes:", length(unique(L$scene)), "\n\n")
cat("=== Likelihood-ratio test: does the band effect depend on vessel size? ===\n"); print(anova(m0, m1))
cat("\n=== m1: band * log_area (centred) + severity, random intercepts scene and vessel ===\n"); print(summary(m1))
cat("\n=== Odds ratios with Wald 95% intervals (m1) ===\n")
fe <- fixef(m1); se <- sqrt(diag(as.matrix(vcov(m1))))
print(round(cbind(OR = exp(fe), lo = exp(fe - 1.96 * se), hi = exp(fe + 1.96 * se)), 3))
cat("\n=== Odds ratios with Wald 95% intervals (m0, no interaction) ===\n")
fe0 <- fixef(m0); se0 <- sqrt(diag(as.matrix(vcov(m0))))
print(round(cbind(OR = exp(fe0), lo = exp(fe0 - 1.96 * se0), hi = exp(fe0 + 1.96 * se0)), 3))
cat("\n=== Predicted detection probability by band at the tercile midpoints (m1, severity = reference, random effects at 0) ===\n")
q <- quantile(exp(L$log_area), c(0.17, 0.5, 0.83))
nd <- expand.grid(band = levels(L$band), area = as.numeric(q), severity = levels(L$severity)[1])
nd$log_area_c <- log(nd$area) - mean(L$log_area)
nd$p <- predict(m1, newdata = nd, re.form = NA, type = "response")
print(round(reshape(nd[, c("band", "area", "p")], idvar = "area", timevar = "band", direction = "wide"), 3))
sink()
cat(readLines(file.path(outdir, "mixed_model.txt")), sep = "\n")
